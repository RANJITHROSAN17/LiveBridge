/** Very small scoring: count keyword / term hits in the query. */
function scoreEntry(entry, terms) {
  let score = 0;

  for (const term of terms) {
    for (const keyword of entry.keywords) {
      if (keyword.includes(term) || term.includes(keyword)) {
        score += 3;
      }
    }

    const haystack = `${entry.title} ${entry.snippet}`.toLowerCase();
    if (haystack.includes(term)) {
      score += 1;
    }
  }

  return score;
}

function searchKnowledgeBase(query) {
  const terms = query
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((term) => term.length > 1);

  const scored = KNOWLEDGE_BASE.map((entry) => ({
    entry,
    score: terms.length > 0 ? scoreEntry(entry, terms) : 0,
  }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 5)
    .map((item) => item.entry);

  // Fall back to a gentle default listing when nothing matches.
  if (scored.length === 0) {
    return KNOWLEDGE_BASE.slice(0, 3);
  }

  return scored;
}

/** Try to produce a spoken answer with the local Ollama model. */
async function askOllama(question, context) {
  const prompt =
    `You are LiveBridge's helpful voice assistant. Answer in ONE short ` +
    `spoken sentence (under 40 words). Be direct and friendly.\n\n` +
    `Context:\n${context}\n\nQuestion: ${question}\nAnswer:`;

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 15000);

    const response = await fetch(OLLAMA_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        model: OLLAMA_MODEL,
        prompt,
        stream: false,
        options: { temperature: 0.3, num_predict: 120 },
      }),
      signal: controller.signal,
    });

    clearTimeout(timeout);

    if (!response.ok) {
      return "";
    }

    const data = await response.json();
    return (data.response || "").trim();
  } catch {
    // Ollama unavailable — caller falls back to the knowledge base.
    return "";
  }
}

function buildFallbackAnswer(query, results) {
  const top = results[0];

  if (!top) {
    return `I could not find anything about "${query}". Try asking about LiveBridge modes, languages, privacy, or exports.`;
  }

  return `${top.snippet.split(". ")[0]}.`;
}

const server = http.createServer(async (req, res) => {
  // CORS: the Vite dev server runs on another port.
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");
  res.setHeader("Content-Type", "application/json; charset=utf-8");

  if (req.method === "OPTIONS") {
    res.writeHead(204);
    res.end();
    return;
  }

  const url = new URL(req.url || "/", `http://localhost:${PORT}`);

  if (url.pathname === "/health") {
    res.writeHead(200);
    res.end(JSON.stringify({ status: "ok", service: "livebridge-search" }));
    return;
  }

  if (url.pathname !== "/search") {
    res.writeHead(404);
    res.end(JSON.stringify({ error: "Not found. Use GET /search?q=..." }));
    return;
  }

  const query = (url.searchParams.get("q") || "").trim();

  if (!query) {
    res.writeHead(400);
    res.end(JSON.stringify({ error: "Missing query parameter q." }));
    return;
  }

  console.log(`[SEARCH] q="${query}"`);

  const results = searchKnowledgeBase(query).map((entry) => ({
    title: entry.title,
    snippet: entry.snippet,
    url: entry.url,
  }));

  const context = results
    .map((entry) => `- ${entry.title}: ${entry.snippet}`)
    .join("\n");

  let answer = await askOllama(query, context);

  if (!answer || answer.length < 5) {
    answer = buildFallbackAnswer(query, results);
  }

  res.writeHead(200);
  res.end(JSON.stringify({ answer, results }));
});

server.listen(PORT, () => {
  console.log(
    `[SEARCH] LiveBridge search API listening on http://localhost:${PORT}/search`
  );
  console.log(
    `[SEARCH] Ollama integration: ${OLLAMA_URL} (model: ${OLLAMA_MODEL})`
  );
});
